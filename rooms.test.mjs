import test from 'node:test';
import assert from 'node:assert/strict';
import { handleRooms } from './rooms.mjs';
const host = { id: 'host', name: 'Host' }, guestUser = { id: 'guest', name: 'Guest' };
test('shared tasks preserve unspecified duration for host and guest', async () => {
  const { data: created } = await call('/api/rooms', { scene: 'sea', minutes: 25 });
  const path = `/api/rooms/${created.id}`;
  const { data: guest } = await call(`${path}/join`, {}, guestUser);
  const task = { id: 'no-estimate', text: 'Read notes', minutes: null };
  assert.equal((await call(`${path}/tasks`, { ...guest, task }, guestUser)).status, 200);
  assert.equal((await call(`${path}/goal`, { ...created, goal: 'Read', tasks: [task] })).status, 200);
  assert.deepEqual((await call(path)).data.tasks, [task]);
});
test('member goal sharing is authorized and stale host timer updates cannot overwrite it', async () => {
  const { data: created } = await call('/api/rooms', { scene: 'sea', minutes: 25, goal: 'Old' });
  const path = `/api/rooms/${created.id}`;
  const { data: guest } = await call(`${path}/join`, {}, guestUser);
  await call(`${path}/goal`, { ...created, goal: 'Old', goalTimer: { remaining: 60000, running: true } });
  assert.equal((await call(`${path}/share-goal`, { ...guest, goal: 'New' }, { id: 'outsider' })).status, 403);
  assert.equal((await call(`${path}/share-goal`, { ...guest, goal: ' ' }, guestUser)).status, 400);
  assert.equal((await call(`${path}/share-goal`, { ...guest, goal: 'New' }, guestUser)).status, 200);
  await call(`${path}/goal`, { ...created, goal: 'Old', baseGoal: 'Old', updateGoal: false, goalTimer: { remaining: 60000, running: true } });
  const result = (await call(path)).data;
  assert.equal(result.goal, 'New'); assert.equal(result.goalTimer, null);
  assert.equal((await call(`${path}/goal`, { ...created, goal: 'Another', baseGoal: 'Old', updateGoal: true })).status, 409);
  await call(`${path}/close`, created);
  assert.equal((await call(`${path}/share-goal`, { ...guest, goal: 'New' }, guestUser)).status, 410);
});
test('members append tasks safely; stale host writes preserve new additions', async () => {
  const { data: created } = await call('/api/rooms', { scene: 'sea', minutes: 25 });
  const path = `/api/rooms/${created.id}`;
  const { data: guest } = await call(`${path}/join`, {}, guestUser);
  const task = { id: 'shared-new', text: 'Prepare notes', minutes: 10 };
  assert.equal((await call(`${path}/tasks`, { ...guest, task }, { id: 'outsider' })).status, 403);
  assert.equal((await call(`${path}/tasks`, { ...guest, task: { ...task, minutes: 0 } }, guestUser)).status, 400);
  assert.equal((await call(`${path}/tasks`, { ...guest, task }, guestUser)).status, 200);
  await call(`${path}/tasks`, { ...guest, task }, guestUser);
  await call(`${path}/goal`, { ...created, goal: 'Updated', tasks: [], baseTaskIds: [] });
  assert.deepEqual((await call(path)).data.tasks, [task]);
  await call(`${path}/goal`, { ...created, goal: 'Updated', tasks: [], baseTaskIds: [task.id] });
  assert.deepEqual((await call(path)).data.tasks, []);
  await call(`${path}/close`, created);
  assert.equal((await call(`${path}/tasks`, { ...guest, task }, guestUser)).status, 410);
});
async function call(path, body, user = host, getProfile = () => null) {
  let result;
  const req = { method: body ? 'POST' : 'GET', headers: { 'content-type': 'application/json' }, async *[Symbol.asyncIterator]() { yield JSON.stringify(body); } };
  await handleRooms(req, {}, new URL(path, 'http://localhost'), (_, status, data) => { result = { status, data }; }, user, getProfile);
  return result;
}
test('room creation, guest privacy, host authorization, start and closure', async () => {
  assert.equal((await call('/api/rooms', { scene: 'unknown', minutes: 10 })).status, 400);
  const { data: created } = await call('/api/rooms', { scene: 'sea', minutes: 25, name: 'Host' });
  const path = `/api/rooms/${created.id}`;
  assert.equal((await call('/api/rooms', { scene: 'sea', minutes: 25 }, null)).status, 401);
  assert.equal((await call(`${path}/join`, {}, null)).status, 401);
  const guest = await call(`${path}/join`, { name: 'Spoofed' }, guestUser);
  assert.equal(guest.status, 200);
  const view = (await call(path)).data;
  assert.equal(view.members.length, 1);
  assert.equal(view.members[0].name, 'Guest');
  const profiles = { host: { name: 'Host', avatar: 'bear', identity: 'private' }, guest: { name: 'Guest', avatar: 'data:image/jpeg;base64,/9j/test', hash: 'private' } };
  let avatars = (await call(path, undefined, guestUser, id => profiles[id])).data;
  assert.equal(avatars.host.avatar, 'bear');
  assert.equal(avatars.members[0].avatar, profiles.guest.avatar);
  assert.equal(avatars.members[0].isSelf, true);
  assert.equal(avatars.host.identity, undefined); assert.equal(avatars.members[0].hash, undefined);
  profiles.host.avatar = 'cat';
  avatars = (await call(path, undefined, guestUser, id => profiles[id])).data;
  assert.equal(avatars.host.avatar, 'cat');
  assert.equal((await call(`${path}/join`, {}, guestUser)).data.memberToken, guest.data.memberToken);
  assert.equal((await call(`${path}/start`, { hostToken: created.hostToken }, guestUser)).status, 403);
  assert.equal(view.hostToken, undefined);
  assert.equal(view.members[0].token, undefined);
  assert.equal((await call(`${path}/start`, { hostToken: guest.data.memberToken })).status, 403);
  assert.equal((await call(`${path}/start`, { hostToken: created.hostToken })).status, 200);
  const started = (await call(path)).data.startedAt;
  assert.equal((await call(path)).data.goal, '');
  assert.equal((await call(`${path}/goal`, { hostToken: created.hostToken, goal: 'Read' }, guestUser)).status, 403);
  assert.equal((await call(`${path}/goal`, { hostToken: created.hostToken, goal: 'Read' })).status, 200);
  assert.equal((await call(path)).data.goal, 'Read');
  const tasks = [{ id: 'step-1', text: 'Read chapter 1', minutes: 15, done: true }];
  assert.equal((await call(`${path}/goal`, { hostToken: created.hostToken, goal: 'Read', tasks }, guestUser)).status, 403);
  assert.equal((await call(`${path}/goal`, { hostToken: created.hostToken, goal: 'Read', tasks })).status, 200);
  assert.deepEqual((await call(path)).data.tasks, [{ id: 'step-1', text: 'Read chapter 1', minutes: 15 }]);
  assert.equal((await call(`${path}/goal`, { hostToken: created.hostToken, goal: 'Read', tasks: [tasks[0], tasks[0]] })).status, 400);
  assert.equal((await call(`${path}/goal`, { hostToken: created.hostToken, goal: 'Read', goalTimer: { remaining: 60000, running: true } })).status, 200);
  let timing = (await call(path)).data;
  assert.ok(Math.abs(timing.goalTimer.deadline - timing.serverNow - 60000) < 1000);
  assert.equal((await call(`${path}/goal`, { hostToken: created.hostToken, goal: 'Read', goalTimer: { remaining: -1, running: true } })).status, 400);
  await call(`${path}/goal`, { hostToken: created.hostToken, goal: 'Read', goalTimer: { remaining: 30000, running: false } });
  assert.equal((await call(path)).data.goalTimer.deadline, null);
  await call(`${path}/goal`, { hostToken: created.hostToken, goal: 'Read', goalTimer: null });
  assert.equal((await call(path)).data.goalTimer, null);
  assert.equal((await call(`${path}/goal-mode`, { memberToken: guest.data.memberToken, goalMode: 'own' }, guestUser)).status, 200);
  assert.equal((await call(path)).data.members[0].goalMode, 'own');
  assert.equal((await call(`${path}/goal-mode`, { memberToken: guest.data.memberToken, goalMode: 'follow' }, guestUser)).status, 200);
  await call(`${path}/start`, { hostToken: created.hostToken });
  assert.equal((await call(path)).data.startedAt, started);
  await call(`${path}/leave`, { memberToken: guest.data.memberToken }, guestUser);
  assert.equal((await call(path)).data.members.length, 0);
  await call(`${path}/close`, { hostToken: created.hostToken });
  assert.equal((await call(`${path}/join`, { name: 'Late' })).status, 410);
});
